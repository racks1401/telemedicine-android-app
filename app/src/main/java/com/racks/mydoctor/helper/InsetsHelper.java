package com.racks.mydoctor.helper;

import android.app.Activity;
import android.view.View;

import androidx.core.graphics.Insets;
import androidx.core.view.ViewCompat;
import androidx.core.view.WindowInsetsCompat;

/**
 * Android 15+ draws apps edge-to-edge (targetSdk 35+), so content would go under the
 * status bar and navigation bar. This pads the activity content so nothing is hidden,
 * and also keeps input fields above the keyboard.
 */
public final class InsetsHelper {

    private InsetsHelper() {
    }

    public static void applySystemBarInsets(Activity activity) {
        View root = activity.findViewById(android.R.id.content);
        ViewCompat.setOnApplyWindowInsetsListener(root, (v, insets) -> {
            Insets bars = insets.getInsets(WindowInsetsCompat.Type.systemBars() | WindowInsetsCompat.Type.displayCutout());
            Insets ime = insets.getInsets(WindowInsetsCompat.Type.ime());
            v.setPadding(bars.left, bars.top, bars.right, Math.max(bars.bottom, ime.bottom));
            return WindowInsetsCompat.CONSUMED;
        });
    }
}
